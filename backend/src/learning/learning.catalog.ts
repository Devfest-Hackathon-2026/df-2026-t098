export function withInterestTags(topics: string[]): string[] {
  const tags = topics
    .map((topic) => topic.trim().toLowerCase())
    .filter(Boolean);
  const interests = Object.entries(INTEREST_TOPICS)
    .filter(([, related]) => tags.some((tag) => related.includes(tag)))
    .map(([interest]) => interest);
  return [...new Set([...tags, ...interests])].slice(0, 12);
}

export function expandInterests(items: string[]): string[] {
  return [
    ...new Set(
      items.flatMap(
        (item) => INTEREST_TOPICS[item] ?? [item.trim().toLowerCase()],
      ),
    ),
  ];
}
